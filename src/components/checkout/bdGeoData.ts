export const GEO_DIVISIONS = BD_GEO.map((d) => d.name);

/** Districts under one division (empty for an unknown or empty division). */
export const districtsOf = (division?: string): string[] => {
  const d = BD_GEO.find((x) => x.name === (division ?? '').trim());
  return d ? d.districts.map((c) => c.name) : [];
};

/** Upazilas under one district within one division. */
export const upazilasOf = (division?: string, district?: string): string[] => {
  const d = BD_GEO.find((x) => x.name === (division ?? '').trim());
  const c = d?.districts.find((x) => x.name === (district ?? '').trim());
  return c ? c.upazilas : [];
};

/** The division a district belongs to — used to back-fill division from a
 *  prefilled district when only the district is known. */
export const divisionOfDistrict = (district?: string): string | undefined => {
  const key = (district ?? '').trim();
  if (!key) return undefined;
  return BD_GEO.find((d) => d.districts.some((c) => c.name === key))?.name;
};
